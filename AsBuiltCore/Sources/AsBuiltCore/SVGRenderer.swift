import Foundation

/// Maps plan meters (y up) onto a screen/page rectangle (y down), preserving aspect ratio.
public struct PlanViewport: Hashable, Sendable {
    public var bounds: Rect2D
    /// Points per meter.
    public var scale: Double
    public var offsetX: Double
    public var offsetY: Double

    public init(bounds: Rect2D, width: Double, height: Double, padding: Double = 16, originX: Double = 0, originY: Double = 0) {
        self.bounds = bounds
        let availableW = max(1, width - 2 * padding)
        let availableH = max(1, height - 2 * padding)
        let bw = max(bounds.width, 1e-6)
        let bh = max(bounds.height, 1e-6)
        let s = min(availableW / bw, availableH / bh)
        scale = s
        // Center the content.
        offsetX = originX + padding + (availableW - bw * s) / 2 - bounds.minX * s
        offsetY = originY + padding + (availableH - bh * s) / 2 + bounds.maxY * s
    }

    /// Plan point -> screen point (y down).
    public func project(_ p: Point2D) -> (x: Double, y: Double) {
        (offsetX + p.x * scale, offsetY - p.y * scale)
    }

    /// Screen point -> plan point.
    public func unproject(x: Double, y: Double) -> Point2D {
        Point2D((x - offsetX) / scale, (offsetY - y) / scale)
    }

    /// Screen-space rotation (degrees, clockwise-positive as in y-down coordinate systems)
    /// for text whose plan rotation is `degrees` counter-clockwise.
    public func screenRotation(_ degrees: Double) -> Double { -degrees }
}

/// Standalone SVG rendering of a plan, with a title block. Used for the `floorplan.svg` export
/// and as a lightweight preview that any browser can open.
public enum SVGRenderer {
    public struct Options: Sendable {
        public var width: Double = 1200
        public var height: Double = 900
        public var title: String = ""
        public var subtitle: String = ""
        public var footer: String = "Generated by AsBuilt. Verify dimensions on site."

        public init(title: String = "", subtitle: String = "") {
            self.title = title
            self.subtitle = subtitle
        }
    }

    public static func render(plan: FloorPlan, units: UnitSystem, options: Options = Options()) -> String {
        let drawing = PlanGeometryBuilder.build(plan, units: units)
        return render(drawing: drawing, options: options)
    }

    public static func render(drawing: PlanDrawing, options: Options) -> String {
        let headerH = options.title.isEmpty ? 0.0 : 70.0
        let footerH = 36.0
        let viewport = PlanViewport(bounds: drawing.bounds, width: options.width,
                                    height: options.height - headerH - footerH, padding: 30, originY: headerH)
        let d = { (v: Double) in UnitFormatter.decimal(v, 2) }
        var s = ""
        s += "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n"
        s += "<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"\(d(options.width))\" height=\"\(d(options.height))\" viewBox=\"0 0 \(d(options.width)) \(d(options.height))\">\n"
        s += "<rect x=\"0\" y=\"0\" width=\"\(d(options.width))\" height=\"\(d(options.height))\" fill=\"#FFFFFF\"/>\n"
        if !options.title.isEmpty {
            s += "<text x=\"30\" y=\"38\" font-family=\"Helvetica, Arial, sans-serif\" font-size=\"26\" font-weight=\"bold\" fill=\"#111827\">\(escape(options.title))</text>\n"
            s += "<text x=\"30\" y=\"60\" font-family=\"Helvetica, Arial, sans-serif\" font-size=\"14\" fill=\"#4B5563\">\(escape(options.subtitle))</text>\n"
            s += "<line x1=\"30\" y1=\"\(d(headerH - 2))\" x2=\"\(d(options.width - 30))\" y2=\"\(d(headerH - 2))\" stroke=\"#111827\" stroke-width=\"1\"/>\n"
        }

        for layer in PlanLayer.allCases {
            let fills = drawing.fills.filter { $0.layer == layer }
            let lines = drawing.lines(on: layer)
            let arcs = drawing.arcs.filter { $0.layer == layer }
            let polys = drawing.polylines.filter { $0.layer == layer }
            let texts = drawing.texts(on: layer)
            if fills.isEmpty && lines.isEmpty && arcs.isEmpty && polys.isEmpty && texts.isEmpty { continue }
            let dash = layer.isDashed ? " stroke-dasharray=\"6 4\"" : ""
            s += "<g id=\"\(layer.rawValue)\" stroke=\"\(layer.hexColor)\" stroke-width=\"\(d(layer.lineWeight))\" fill=\"none\" stroke-linecap=\"round\"\(dash)>\n"
            for f in fills {
                let pts = f.points.map { viewport.project($0) }.map { "\(d($0.x)),\(d($0.y))" }.joined(separator: " ")
                s += "<polygon points=\"\(pts)\" fill=\"#D1D5DB\" stroke=\"none\"/>\n"
            }
            for l in lines {
                let a = viewport.project(l.a)
                let b = viewport.project(l.b)
                s += "<line x1=\"\(d(a.x))\" y1=\"\(d(a.y))\" x2=\"\(d(b.x))\" y2=\"\(d(b.y))\"/>\n"
            }
            for arc in arcs {
                let r = arc.radius * viewport.scale
                let startPlan = arc.center + Point2D(cos(arc.startAngle * .pi / 180), sin(arc.startAngle * .pi / 180)) * arc.radius
                let endPlan = arc.center + Point2D(cos(arc.endAngle * .pi / 180), sin(arc.endAngle * .pi / 180)) * arc.radius
                let a = viewport.project(startPlan)
                let b = viewport.project(endPlan)
                var sweep = arc.endAngle - arc.startAngle
                if sweep < 0 { sweep += 360 }
                let large = sweep > 180 ? 1 : 0
                // CCW in plan (y up) is sweep-flag 0 in SVG (y down).
                s += "<path d=\"M \(d(a.x)) \(d(a.y)) A \(d(r)) \(d(r)) 0 \(large) 0 \(d(b.x)) \(d(b.y))\" stroke-dasharray=\"4 3\"/>\n"
            }
            for p in polys {
                let pts = p.points.map { viewport.project($0) }.map { "\(d($0.x)),\(d($0.y))" }.joined(separator: " ")
                s += p.closed ? "<polygon points=\"\(pts)\"/>\n" : "<polyline points=\"\(pts)\"/>\n"
            }
            for t in texts {
                let p = viewport.project(t.position)
                let size = max(7, t.height * viewport.scale * 1.35)
                let weight = (t.role == .roomName || t.role == .dimension) ? " font-weight=\"bold\"" : ""
                let fill = t.layer.hexColor
                let rot = viewport.screenRotation(t.rotation)
                let transform = abs(rot) > 1e-9 ? " transform=\"rotate(\(d(rot)) \(d(p.x)) \(d(p.y)))\"" : ""
                s += "<text x=\"\(d(p.x))\" y=\"\(d(p.y))\" font-family=\"Helvetica, Arial, sans-serif\" font-size=\"\(d(size))\"\(weight) fill=\"\(fill)\" stroke=\"none\" text-anchor=\"middle\" dominant-baseline=\"central\"\(transform)>\(escape(t.text))</text>\n"
            }
            s += "</g>\n"
        }
        s += "<text x=\"30\" y=\"\(d(options.height - 14))\" font-family=\"Helvetica, Arial, sans-serif\" font-size=\"12\" fill=\"#6B7280\">\(escape(options.footer))</text>\n"
        s += "</svg>\n"
        return s
    }

    public static func escape(_ text: String) -> String {
        text.replacingOccurrences(of: "&", with: "&amp;")
            .replacingOccurrences(of: "<", with: "&lt;")
            .replacingOccurrences(of: ">", with: "&gt;")
            .replacingOccurrences(of: "\"", with: "&quot;")
    }
}
